const renderSection = (s: ResumeSection, L: OutputLang, df: string, A: Emitter) => {
  const P = pick;
  switch (s.kind) {
    case "summary": {
      const t = s.data as { fa: string; en: string };
      const v = P(t, L);
      if (v) A(v.replace(/\n+/g, "\\\\ "));
      break;
    }
    case "skills": {
      const cats = s.data as { id: string; name: { fa: string; en: string }; skills: { name: string; level: string; years: string }[] }[];
      for (const c of cats) {
        const items = c.skills.map((sk) => {
          let label = sk.name;
          const extra: string[] = [];
          if (sk.level) extra.push(sk.level);
          if (sk.years) extra.push(sk.years + (L === "fa" ? " سال" : "y"));
          return label + (extra.length ? " (" + extra.join(", ") + ")" : "");
        });
        A(bib(P(c.name, L)) + ": " + chipList(items.join(", ")));
      }
      break;
    }
    case "experience": {
      const list = s.data as never as {
        id: string; title: { fa: string; en: string }; company: { fa: string; en: string };
        location: { fa: string; en: string }; employmentType: string;
        start: string; end: string; present: boolean;
        responsibilities: Bi; achievements: Bi; technologies: Bi; projects: Bi;
      }[];
      for (const e of list) {
        A("\\textbf{" + bib(P(e.title, L)) + "}" +
          (P(e.company, L) ? " --- " + bib(P(e.company, L)) : "") + " \\hfill " + esc(formatDateRange(e, L, df)));
        const sub = [P(e.location, L), EMPLOYMENT_TYPE_LABELS[L][e.employmentType] || ""].filter(Boolean).join(" · ");
        if (sub) A("\\textit{" + bib(sub) + "}");
        A(itemize(P(e.responsibilities, L)));
        A(itemize(P(e.achievements, L)));
        if (P(e.technologies, L)) A("\\textit{" + (L === "fa" ? "فناوری‌ها" : "Technologies") + "}: " + chipList(P(e.technologies, L)));
        if (P(e.projects, L)) A("\\textit{" + (L === "fa" ? "پروژه‌ها" : "Projects") + "}: " + bib(P(e.projects, L)));
        A("");
      }
      break;
    }
    case "education": {
      const list = s.data as never as {
        id: string; degree: Bi; field: Bi; university: Bi; location: Bi;
        start: string; end: string; present: boolean; gpa: Bi;
        thesisTitle: Bi; thesisDescription: Bi; courses: Bi; achievements: Bi;
      }[];
      for (const e of list) {
        A("\\textbf{" + bib(P(e.degree, L)) + "}" +
          (P(e.field, L) ? " --- " + bib(P(e.field, L)) : "") + " \\hfill " + esc(formatDateRange(e, L, df)));
        const sub = [P(e.university, L), P(e.location, L),
          (e.gpa.fa || e.gpa.en) ? (L === "fa" ? "معدل: " : "GPA: ") + P(e.gpa, L) : ""]
          .filter(Boolean).join(" · ");
        if (sub) A("\\textit{" + bib(sub) + "}");
        if (P(e.thesisTitle, L)) A("\\textit{" + (L === "fa" ? "پایان‌نامه" : "Thesis") + "}: " + bib(P(e.thesisTitle, L)));
        A(itemize(P(e.thesisDescription, L)));
        if (P(e.courses, L)) A("\\textit{" + (L === "fa" ? "دروس" : "Courses") + "}: " + bib(P(e.courses, L)));
        A(itemize(P(e.achievements, L)));
        A("");
      }
      break;
    }
    case "projects": {
      const list = s.data as never as {
        id: string; name: Bi; role: Bi; organization: Bi;
        start: string; end: string; present: boolean;
        description: Bi; responsibilities: Bi; achievements: Bi;
        technologies: Bi; software: Bi; hardware: Bi; results: Bi;
        links: { id: string; label: string; url: string }[];
      }[];
      for (const e of list) {
        A("\\textbf{" + bib(P(e.name, L)) + "}" +
          (P(e.role, L) ? " --- " + bib(P(e.role, L)) : "") + " \\hfill " + esc(formatDateRange(e, L, df)));
        if (P(e.organization, L)) A("\\textit{" + bib(P(e.organization, L)) + "}");
        if (P(e.description, L)) A(bib(P(e.description, L)));
        A(itemize(P(e.responsibilities, L)));
        A(itemize(P(e.achievements, L)));
        if (P(e.technologies, L)) A("\\textit{" + (L === "fa" ? "فناوری‌ها" : "Technologies") + "}: " + chipList(P(e.technologies, L)));
        if (P(e.software, L)) A("\\textit{" + (L === "fa" ? "نرم‌افزار" : "Software") + "}: " + chipList(P(e.software, L)));
        if (P(e.hardware, L)) A("\\textit{" + (L === "fa" ? "سخت‌افزار" : "Hardware") + "}: " + chipList(P(e.hardware, L)));
        if (P(e.results, L)) A(itemize(P(e.results, L)));
        for (const l of e.links || []) {
          if (l.url) A("\\href{" + l.url + "}{" + esc(l.label || l.url) + "}");
        }
        A("");
      }
      break;
    }
    case "research": {
      const list = s.data as never as {
        id: string; position: Bi; institution: Bi; topic: Bi;
        start: string; end: string; present: boolean;
        description: Bi; methodology: Bi; tools: Bi; results: Bi;
      }[];
      for (const e of list) {
        A("\\textbf{" + bib(P(e.topic, L) || P(e.position, L)) + "} \\hfill " + esc(formatDateRange(e, L, df)));
        const sub = [P(e.position, L), P(e.institution, L)].filter(Boolean).join(" · ");
        if (sub) A("\\textit{" + bib(sub) + "}");
        if (P(e.description, L)) A(bib(P(e.description, L)));
        if (P(e.methodology, L)) A("\\textit{" + (L === "fa" ? "روش" : "Methodology") + "}: " + bib(P(e.methodology, L)));
        if (P(e.tools, L)) A("\\textit{" + (L === "fa" ? "ابزارها" : "Tools") + "}: " + chipList(P(e.tools, L)));
        if (P(e.results, L)) A(itemize(P(e.results, L)));
        A("");
      }
      break;
    }
    case "publications": {
      const list = s.data as never as {
        id: string; title: Bi; authors: Bi; venue: Bi; year: string; doi: string; url: string;
      }[];
      for (const e of list) {
        const bits: string[] = [];
        bits.push("\\textbf{" + bib(P(e.title, L)) + "}");
        if (P(e.authors, L)) bits.push(bib(P(e.authors, L)));
        if (P(e.venue, L)) bits.push("\\textit{" + bib(P(e.venue, L)) + "}");
        if (e.year) bits.push("(" + esc(e.year) + ")");
        let line = bits.join(", ");
        if (e.doi) line += ". \\href{https://doi.org/" + esc(e.doi) + "}{doi:" + esc(e.doi) + "}";
        else if (e.url) line += ". \\href{" + e.url + "}{" + esc(e.url.replace(/^https?:\/\//, "")) + "}";
        A("\\noindent " + line + "\\\\[2pt]");
      }
      break;
    }
    case "conferences": {
      const list = s.data as never as { id: string; name: Bi; talk: Bi; location: Bi; date: string; role: Bi }[];
      for (const e of list) {
        A("\\textbf{" + bib(P(e.talk, L) || P(e.name, L)) + "} \\hfill " + esc(formatDate(e.date, L, df)));
        const sub = [P(e.name, L), P(e.location, L), P(e.role, L)].filter(Boolean).join(" · ");
        if (sub) A("\\textit{" + bib(sub) + "}");
      }
      break;
    }
    case "certifications": {
      const list = s.data as never as { id: string; name: Bi; issuer: Bi; issueDate: string; expiryDate: string; credentialId: string; url: string }[];
      for (const e of list) {
        const dd = [e.issueDate ? formatDate(e.issueDate, L, df) : "", e.expiryDate ? formatDate(e.expiryDate, L, df) : ""].filter(Boolean).join(" -- ");
        A("\\textbf{" + bib(P(e.name, L)) + "}" +
          (P(e.issuer, L) ? " --- " + bib(P(e.issuer, L)) : "") + " \\hfill " + esc(dd));
        const sub = [e.credentialId ? (L === "fa" ? "شناسه: " : "ID: ") + esc(e.credentialId) : "",
          e.url ? "\\href{" + e.url + "}{" + esc(e.url.replace(/^https?:\/\//, "")) + "}" : ""].filter(Boolean).join(" · ");
        if (sub) A("\\textit{" + sub + "}");
      }
      break;
    }
    case "awards": {
      const list = s.data as never as { id: string; name: Bi; organization: Bi; date: string; description: Bi }[];
      for (const e of list) {
        A("\\textbf{" + bib(P(e.name, L)) + "}" +
          (P(e.organization, L) ? " --- " + bib(P(e.organization, L)) : "") + " \\hfill " + esc(formatDate(e.date, L, df)));
        if (P(e.description, L)) A(bib(P(e.description, L)));
      }
      break;
    }
    case "languages": {
      const list = s.data as never as { id: string; language: Bi; reading: string; writing: string; speaking: string; listening: string; overall: string }[];
      for (const e of list) {
        const o = e.overall ? (e.overall === "native" ? (L === "fa" ? "زبان مادری" : "Native") : e.overall) : "";
        const det = [e.reading, e.writing, e.speaking, e.listening].filter(Boolean).join("/");
        A("\\textbf{" + bib(P(e.language, L)) + "}" +
          (o ? ": " + bib(o) : "") + (det ? " (" + esc(det) + ")" : ""));
      }
      break;
    }
    case "courses": {
      const list = s.data as never as { id: string; name: Bi; provider: Bi; date: string; duration: Bi; description: Bi }[];
      for (const e of list) {
        const dd = [formatDate(e.date, L, df), P(e.duration, L)].filter(Boolean).join(" · ");
        A("\\textbf{" + bib(P(e.name, L)) + "}" +
          (P(e.provider, L) ? " --- " + bib(P(e.provider, L)) : "") + (dd ? " \\hfill " + esc(dd) : ""));
        if (P(e.description, L)) A(bib(P(e.description, L)));
      }
      break;
    }
    case "volunteer": {
      const list = s.data as never as { id: string; role: Bi; organization: Bi; location: Bi; start: string; end: string; present: boolean; description: Bi }[];
      for (const e of list) {
        A("\\textbf{" + bib(P(e.role, L)) + "}" +
          (P(e.organization, L) ? " --- " + bib(P(e.organization, L)) : "") + " \\hfill " + esc(formatDateRange(e, L, df)));
        if (P(e.location, L)) A("\\textit{" + bib(P(e.location, L)) + "}");
        if (P(e.description, L)) A(bib(P(e.description, L)));
      }
      break;
    }
    case "memberships": {
      const list = s.data as never as { id: string; organization: Bi; role: Bi; start: string; end: string; present: boolean; description: Bi }[];
      for (const e of list) {
        A("\\textbf{" + bib(P(e.organization, L)) + "}" +
          (P(e.role, L) ? " --- " + bib(P(e.role, L)) : "") + " \\hfill " + esc(formatDateRange(e, L, df)));
        if (P(e.description, L)) A(bib(P(e.description, L)));
      }
      break;
    }
    case "teaching": {
      const list = s.data as never as { id: string; role: Bi; institution: Bi; course: Bi; start: string; end: string; present: boolean; description: Bi }[];
      for (const e of list) {
        A("\\textbf{" + bib(P(e.role, L)) + "}" +
          (P(e.course, L) ? " --- " + bib(P(e.course, L)) : "") + " \\hfill " + esc(formatDateRange(e, L, df)));
        if (P(e.institution, L)) A("\\textit{" + bib(P(e.institution, L)) + "}");
        if (P(e.description, L)) A(bib(P(e.description, L)));
      }
      break;
    }
    case "patents": {
      const list = s.data as never as { id: string; title: Bi; inventors: Bi; office: Bi; number: string; date: string; status: Bi; description: Bi }[];
      for (const e of list) {
        A("\\textbf{" + bib(P(e.title, L)) + "} \\hfill " + esc(formatDate(e.date, L, df)));
        const sub = [P(e.inventors, L), P(e.office, L),
          e.number ? (L === "fa" ? "شماره " : "No. ") + esc(e.number) : "", P(e.status, L)]
          .filter(Boolean).join(" · ");
        if (sub) A("\\textit{" + bib(sub) + "}");
        if (P(e.description, L)) A(bib(P(e.description, L)));
      }
      break;
    }
    case "interests":
    case "hobbies": {
      const t = s.data as { fa: string; en: string };
      const v = P(t, L);
      if (v) A(v.replace(/\n+/g, ", "));
      break;
    }
    case "references": {
      const list = s.data as never as { id: string; name: Bi; position: Bi; organization: Bi; contact: Bi }[];
      for (const e of list) {
        A("\\textbf{" + bib(P(e.name, L)) + "}" +
          (P(e.position, L) ? " --- " + bib(P(e.position, L)) : ""));
        const sub = [P(e.organization, L), P(e.contact, L)].filter(Boolean).join(" · ");
        if (sub) A("\\textit{" + bib(sub) + "}");
      }
      break;
    }
    case "custom": {
      const d = s.data as { title: Bi; entries: { id: string; title: Bi; subtitle: Bi; date: Bi; body: Bi }[] };
      if (P(d.title, L)) A(bib(P(d.title, L)));
      for (const e of d.entries || []) {
        A("\\textbf{" + bib(P(e.title, L)) + "}" +
          (P(e.subtitle, L) ? " --- " + bib(P(e.subtitle, L)) : "") +
          (P(e.date, L) ? " \\hfill " + bib(P(e.date, L)) : ""));
        if (P(e.body, L)) A(bib(P(e.body, L)));
        A("");
      }
      break;
    }
    default:
      break;
  }
};

