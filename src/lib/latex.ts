const esc = (s: string): string =>
  s
    .replace(/\\/g, "\\textbackslash{}")
    .replace(/([&%$#_{}])/g, "\\$1")
    .replace(/~/g, "\\textasciitilde{}")
    .replace(/\^/g, "\\textasciicircum{}");

const bib = (s: string) => esc(s).replace(/\n+/g, " ");

const itemize = (text: string): string => {
  const items = text.split(/\n|•/).map((x) => x.trim()).filter(Boolean);
  if (!items.length) return "";
  const body = items.map((i) => "  \\item " + bib(i)).join("\n");
  return "\\begin{itemize}[leftmargin=1.2em,nosep]\n" + body + "\n\\end{itemize}";
};

const chipList = (s: string): string =>
  s.split(/[,،;؛|\n]/).map((x) => x.trim()).filter(Boolean).map(bib).join(", ");

type Emitter = (...xs: (string | false | undefined | null)[]) => void;

