export const generateLaTeX = (r: Resume, L: OutputLang): string => {
  return [...PREAMBLE_HEAD(r, L), ...DOC_BODY(r, L)].join("\n");
};

const README = (r: Resume, L: OutputLang): string => {
  const fa = L === "fa";
  return [
    "# " + (fa ? "رزومه فارسی" : "English Resume") + " — LaTeX",
    "",
    fa
      ? "این بسته با XeLaTeX کامپایل می‌شود:"
      : "Compile with XeLaTeX:",
    "",
    "    xelatex resume.tex",
    "",
    fa
      ? "فونت وزیرمتن در پوشه fonts/ قرار دارد و به‌صورت محلی بارگذاری می‌شود."
      : "The Vazirmatn font ships in fonts/ and is loaded locally.",
    "",
    fa
      ? "فایل اصلی: resume.tex — می‌توانید متن را مستقیماً ویرایش کنید."
      : "Main file: resume.tex — edit the text directly.",
    "",
    fa
      ? "نیازمندی‌ها: TeX Live یا MiKTeX با بسته‌های polyglossia و bidi (برای نسخه فارسی)."
      : "Requirements: TeX Live or MiKTeX with polyglossia and bidi (Persian version).",
  ].join("\n");
};

const FONT_FILES = [
  "Vazirmatn-Regular.ttf",
  "Vazirmatn-Medium.ttf",
  "Vazirmatn-Bold.ttf",
];

export const buildLatexZip = async (r: Resume, L: OutputLang): Promise<Blob> => {
  const JSZip = (await import("jszip")).default;
  const zip = new JSZip();
  zip.file("resume.tex", generateLaTeX(r, L));
  zip.file("README.md", README(r, L));
  const fonts = zip.folder("fonts");
  if (fonts) {
    // basePath-aware (GitHub Pages hosts the app under /<repo>)
    const bp = process.env.NEXT_PUBLIC_BASE_PATH || "";
    for (const f of FONT_FILES) {
      try {
        const res = await fetch(`${bp}/fonts/${f}`);
        if (res.ok) {
          fonts.file(f, await res.arrayBuffer());
        }
      } catch {
        // font fetch failed — the .tex still compiles if Vazirmatn is installed system-wide
      }
    }
  }
  return zip.generateAsync({ type: "blob" });
};

