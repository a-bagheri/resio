const DICTS: Record<UiLang, Dict> = { fa, en };

// ============================================================
// Provider + hook
// ============================================================

interface I18nCtx {
  lang: UiLang;
  setLang: (l: UiLang) => void;
  t: (k: string) => string;
  dir: "rtl" | "ltr";
}

const Ctx = createContext<I18nCtx | null>(null);
const STORAGE_KEY = "resio.uiLang";
// pre-rebrand key, kept as a read-only fallback so users keep their choice
const LEGACY_STORAGE_KEY = "biresume.uiLang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<UiLang>("fa");

  useEffect(() => {
    const saved = localStorage.getItem(STORAGE_KEY) ?? localStorage.getItem(LEGACY_STORAGE_KEY);
    if (saved === "fa" || saved === "en") setLangState(saved);
  }, []);

  const setLang = (l: UiLang) => {
    setLangState(l);
    localStorage.setItem(STORAGE_KEY, l);
  };

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "fa" ? "rtl" : "ltr";
  }, [lang]);

  const value: I18nCtx = {
    lang,
    setLang,
    t: (k: string) => DICTS[lang][k] ?? DICTS.en[k] ?? k,
    dir: lang === "fa" ? "rtl" : "ltr",
  };

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n outside provider");
  return ctx;
}

